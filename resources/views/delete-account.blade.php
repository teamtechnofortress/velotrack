<h1>Delete your Drivio account</h1>
<p>Drivio is a vehicle and expense tracking app by TechnoFortress. You can delete your Drivio account and the data stored with it at any time.</p>

<h2>Option 1: delete inside the app (fastest)</h2>
<ol>
<li>Open Drivio and sign in.</li>
<li>Go to <strong>More</strong> &rarr; <strong>My account</strong>.</li>
<li>Tap <strong>Delete account</strong>, enter your password and confirm.</li>
</ol>
<p>Your account is deleted immediately.</p>

<h2>Option 2: request deletion by email</h2>
<p>If you can no longer open the app, email <a href="mailto:team.technofortress@gmail.com?subject=Drivio%20account%20deletion">team.technofortress@gmail.com</a> from the email address of your Drivio account with the subject &ldquo;Drivio account deletion&rdquo;. We delete the account within 30 days of confirming the request.</p>

<h2>What is deleted</h2>
<ul>
<li>Your account details: name, email address and password.</li>
<li>All vehicles, fuel, service and expense entries, reminders and inspections synced to our server.</li>
<li>Backups, fleet or driver records and any sign-in sessions linked to your account.</li>
</ul>

<h2>What is kept</h2>
<p>Nothing linked to your account is kept after deletion. Routine server backups may hold copies for up to 30 days before they are overwritten. Data stored only on your phone is removed when you uninstall the app.</p>

<p>See also our <a href="https://technofortress.net/privacy-policy/drivio-privacy-policy/">Privacy Policy</a>.</p>
